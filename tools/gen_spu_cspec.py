"""Generate data/languages/spu.cspec (SPU ABI as implemented by GCC's spu port).

Arguments travel in the preferred slots of r3-r74: 1-4 byte values in word 0, 5-8 byte values
in doubleword 0, vectors (and quadword values) in the whole register.  Return values use r3 the
same way.  r80-r127 and the stack pointer are callee-saved; r0-r79 are volatile.
Usage: tools/gen_spu_cspec.py > data/languages/spu.cspec
"""


def reg(n):
    return {0: 'lr', 1: 'sp'}.get(n, 'r%d' % n)


def group(n, indent):
    p = ' ' * indent
    return '\n'.join([
        p + '<group>',
        p + '  <pentry minsize="1" maxsize="4" extension="inttype"><register name="%s_w0"/></pentry>' % reg(n),
        p + '  <pentry minsize="5" maxsize="8"><register name="%s_d0"/></pentry>' % reg(n),
        p + '  <pentry minsize="9" maxsize="16"><register name="%s"/></pentry>' % reg(n),
        p + '</group>'])


def main():
    o = []
    o.append('<?xml version="1.0" encoding="UTF-8"?>')
    o.append('<!-- Generated by tools/gen_spu_cspec.py -->')
    o.append('<compiler_spec>')
    o.append('  <data_organization>')
    for k, v in (('absolute_max_alignment', 16), ('machine_alignment', 16), ('default_alignment', 1),
                 ('default_pointer_alignment', 4), ('pointer_size', 4), ('char_type', None),
                 ('short_size', 2), ('integer_size', 4), ('long_size', 4), ('long_long_size', 8),
                 ('float_size', 4), ('double_size', 8), ('long_double_size', 8)):
        if k == 'char_type':
            o.append('    <char_type signed="false"/>')
        else:
            o.append('    <%s value="%d"/>' % (k, v))
    o.append('    <size_alignment_map>')
    for s in (1, 2, 4, 8, 16):
        o.append('      <entry size="%d" alignment="%d"/>' % (s, s))
    o.append('    </size_alignment_map>')
    o.append('  </data_organization>')
    o.append('  <global>')
    o.append('    <range space="ram"/>')
    o.append('  </global>')
    o.append('  <stackpointer register="sp_w0" space="ram"/>')
    o.append('  <returnaddress>')
    o.append('    <register name="lr_w0"/>')
    o.append('  </returnaddress>')
    o.append('  <default_proto>')
    o.append('    <prototype name="__stdcall" extrapop="0" stackshift="0">')
    o.append('      <input>')
    for n in range(3, 75):
        o.append(group(n, 8))
    o.append('        <pentry minsize="1" maxsize="500" align="16">')
    o.append('          <addr offset="32" space="stack"/>')
    o.append('        </pentry>')
    o.append('      </input>')
    o.append('      <output>')
    o.extend(l for l in group(3, 8).split('\n') if 'group>' not in l)
    o.append('      </output>')
    o.append('      <unaffected>')
    o.append('        <register name="sp"/>')
    for n in range(80, 128):
        o.append('        <register name="%s"/>' % reg(n))
    o.append('      </unaffected>')
    o.append('      <killedbycall>')
    for n in [0] + list(range(2, 80)):
        o.append('        <register name="%s"/>' % reg(n))
    o.append('      </killedbycall>')
    o.append('    </prototype>')
    o.append('  </default_proto>')
    o.append('</compiler_spec>')
    print('\n'.join(o))


if __name__ == '__main__':
    main()
